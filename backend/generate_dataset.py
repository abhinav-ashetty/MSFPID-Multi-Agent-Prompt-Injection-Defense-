# We need at least 100 of each, but we have more than 100 in each list.
# Let's take the first 100 of each.
benign_examples = benign_examples[:100]
malicious_examples = malicious_examples[:100]

# Create rows with label
rows = []
for text in benign_examples:
    rows.append([text, 0])
for text in malicious_examples:
    rows.append([text, 1])

# Shuffle the rows
random.seed(42)
random.shuffle(rows)

# Write to CSV
with open('data/security_prompts.csv', 'w', newline='', encoding='utf-8') as f:
    writer = csv.writer(f)
    writer.writerow(['text', 'label'])
    writer.writerows(rows)

print(f"Generated dataset with {len(rows)} examples.")
print(f"Benign: {sum(1 for _, label in rows if label == 0)}")
print(f"Malicious: {sum(1 for _, label in rows if label == 1)}")